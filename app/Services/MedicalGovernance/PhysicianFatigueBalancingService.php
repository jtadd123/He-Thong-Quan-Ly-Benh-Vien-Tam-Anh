    public static function calculateDoctorFatigueScore(int $doctorId, array $recentShifts): array
    {
        $baseScore = 20.0;
        $nightShiftCount = 0;
        foreach ($recentShifts as $shift) {
            if (($shift['shift_type'] ?? '') === 'night') {
                $nightShiftCount++;
                $baseScore += 18.5;
            } else {
                $baseScore += 5.0;
            }
        }

        $riskTier = 'Bình thường (Low Risk)';
        if ($baseScore > 75.0) {
            $riskTier = 'Cảnh báo kiệt sức nghiêm trọng (High Burnout Risk)';
        } elseif ($baseScore > 50.0) {
            $riskTier = 'Mệt mỏi trung bình (Moderate Fatigue)';
        }

        return [
            'doctor_id' => $doctorId,
            'fatigue_score' => round($baseScore, 2),
            'risk_tier' => $riskTier,
            'night_shift_count' => $nightShiftCount,
            'is_eligible_for_overtime' => $baseScore <= 70.0,
            'recommended_rest_hours' => $nightShiftCount >= 2 ? 36 : 12,
        ];
    }

